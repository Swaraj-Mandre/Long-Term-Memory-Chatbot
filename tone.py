"""
Turns a detected emotion into instructions for how the bot should reply.

This is a plain lookup table on purpose. Anyone can read it, change one line,
and see the effect. The instruction is added to the system prompt (see
build_messages in chat_engine.py), so the LLM writes the reply in that tone.
"""

# For each emotion: a short name for the interface, and the instruction the
# LLM actually receives.
TONE_RULES = {
    "joy": {
        "name": "Cheerful",
        "instruction": "The user is happy. Match their energy: be warm and "
                       "upbeat, and share in their good news briefly.",
    },
    "sadness": {
        "name": "Gentle",
        "instruction": "The user is sad. Be gentle and calm. Acknowledge the "
                       "feeling first, before any advice. Use short, kind "
                       "sentences. No jokes, and do not rush to fix things.",
    },
    "anger": {
        "name": "Calm",
        "instruction": "The user is frustrated or angry. Stay calm and "
                       "respectful. Do not argue or get defensive. Acknowledge "
                       "the frustration, then help with the actual problem.",
    },
    "fear": {
        "name": "Reassuring",
        "instruction": "The user is worried or anxious. Be steady and "
                       "reassuring. Offer one small, concrete next step "
                       "rather than a long list.",
    },
    "surprise": {
        "name": "Curious",
        "instruction": "The user is surprised. Respond with curiosity and "
                       "help them make sense of what happened.",
    },
    "disgust": {
        "name": "Understanding",
        "instruction": "The user is put off by something. Acknowledge it "
                       "without judging, and stay neutral and helpful.",
    },
    "neutral": {
        "name": "Friendly",
        "instruction": "Be friendly, clear and to the point.",
    },
}

# Added on top of the tone when the safety level is "concern".
CONCERN_INSTRUCTION = (
    "The user has seemed low for a while. Gently check in on how they are "
    "really doing. If it fits naturally, mention that talking to someone they "
    "trust, or a helpline such as Tele-MANAS (14416), can help. Do not lecture."
)


def choose_tone(emotion, safety_level):
    """Return {"name", "instruction"} for this emotion and safety level."""
    if safety_level == 2:
        return {
            "name": "Fixed safe reply",
            "instruction": "Not generated by the LLM. A reviewed message with "
                           "helpline numbers is shown instead.",
        }

    rule = dict(TONE_RULES.get(emotion, TONE_RULES["neutral"]))
    if safety_level == 1:
        rule["name"] = rule["name"] + " + check-in"
        rule["instruction"] = rule["instruction"] + " " + CONCERN_INSTRUCTION
    return rule
